// Generates src/data/mushaf/fontModules.ts from the bundled QCF page fonts.
//
// Metro requires every asset reference to be statically analyzable, so a
// 604-entry `require()` map is generated once and committed. Re-run this
// whenever assets/mushaf/fonts changes:
//
//   node scripts/generate-font-map.mjs
//
import { readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const fontsDir = join(root, 'assets', 'mushaf', 'fonts');
const outFile = join(root, 'src', 'data', 'mushaf', 'fontModules.ts');

const files = readdirSync(fontsDir);
const pageFiles = files
  .map((name) => {
    const match = /^QCF_P(\d{3})\.woff2$/.exec(name);
    return match ? { page: Number(match[1]), name } : null;
  })
  .filter(Boolean)
  .sort((a, b) => a.page - b.page);

if (pageFiles.length !== 604) {
  throw new Error(`Expected 604 page fonts, found ${pageFiles.length}`);
}

const pageLines = pageFiles
  .map(
    ({ page, name }) =>
      `  ${page}: require('../../../assets/mushaf/fonts/${name}'),`
  )
  .join('\n');

const contents = `/**
 * AUTO-GENERATED by scripts/generate-font-map.mjs — do not edit by hand.
 *
 * Static asset map for the 604 QCF Madani page fonts plus the two ornament
 * fonts used by the Mushaf renderer. Metro can only resolve literal
 * \`require()\` calls, so this map exists to keep the rest of the renderer
 * dynamic.
 */
/* eslint-disable @typescript-eslint/no-require-imports */

export type FontAssetModule = number | string;

export const MUSHAF_PAGE_FONTS: Record<number, FontAssetModule> = {
${pageLines}
};

export const MUSHAF_ORNAMENT_FONTS: Record<'surahHeader' | 'bismillah', FontAssetModule> = {
  surahHeader: require('../../../assets/mushaf/fonts/surah-header.woff2'),
  bismillah: require('../../../assets/mushaf/fonts/bismillah.woff2'),
};
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, contents, 'utf8');
console.log(`Wrote ${outFile} with ${pageFiles.length} page fonts.`);
